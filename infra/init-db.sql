-- Script de Inicialização Automatizada do Banco de Dados PostgreSQL (Local / Container)
-- SGA - Sistema de Gestão de Ambientes

CREATE TABLE IF NOT EXISTS niveis (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS tipos_curso (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nivel_id BIGINT NOT NULL REFERENCES niveis(id),
  nome TEXT NOT NULL,
  UNIQUE (nivel_id, nome)
);

CREATE TABLE IF NOT EXISTS cursos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_curso_id BIGINT NOT NULL REFERENCES tipos_curso(id),
  nome TEXT NOT NULL,
  UNIQUE (tipo_curso_id, nome)
);

CREATE TABLE IF NOT EXISTS docentes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registro TEXT UNIQUE,
  nome TEXT NOT NULL UNIQUE,
  area TEXT
);

CREATE TABLE IF NOT EXISTS componentes_curriculares (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sigla TEXT NOT NULL,
  nome TEXT NOT NULL,
  UNIQUE (sigla, nome)
);

CREATE TABLE IF NOT EXISTS turmas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  curso_id BIGINT REFERENCES cursos(id),
  codigo TEXT NOT NULL UNIQUE,
  nome TEXT NOT NULL DEFAULT '',
  carga_horaria INTEGER NOT NULL CHECK (carga_horaria > 0),
  turno TEXT NOT NULL,
  situacao TEXT NOT NULL,
  horario_inicio TIME,
  horario_fim TIME,
  periodo_inicio DATE,
  periodo_fim DATE,
  CHECK (horario_fim IS NULL OR horario_inicio IS NULL OR horario_fim > horario_inicio),
  CHECK (periodo_fim IS NULL OR periodo_inicio IS NULL OR periodo_fim >= periodo_inicio)
);

CREATE TABLE IF NOT EXISTS turma_componentes_docentes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turma_id BIGINT NOT NULL REFERENCES turmas(id) ON DELETE CASCADE,
  componente_id BIGINT NOT NULL REFERENCES componentes_curriculares(id),
  docente_id BIGINT REFERENCES docentes(id),
  carga_horaria INTEGER NOT NULL CHECK (carga_horaria > 0)
);

CREATE TABLE IF NOT EXISTS ambientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo TEXT NOT NULL UNIQUE,
  nome TEXT NOT NULL,
  tipo TEXT DEFAULT 'Sala Teórica',
  local TEXT DEFAULT 'Bloco A',
  capacidade INTEGER DEFAULT 35 CHECK (capacidade > 0),
  status TEXT NOT NULL DEFAULT 'Disponível'
);

CREATE TABLE IF NOT EXISTS alocacoes_ambiente (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ambiente_id BIGINT NOT NULL REFERENCES ambientes(id),
  turma_id BIGINT REFERENCES turmas(id),
  docente_id BIGINT REFERENCES docentes(id),
  dia_semana TEXT NOT NULL,
  horario_inicio TIME NOT NULL,
  horario_fim TIME NOT NULL,
  disciplina TEXT
);

CREATE TABLE IF NOT EXISTS sugestoes_manutencao (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ambiente_id BIGINT REFERENCES ambientes(id),
  ambiente_codigo TEXT,
  solicitante TEXT NOT NULL,
  descricao TEXT NOT NULL,
  tipo_ocorrencia TEXT NOT NULL,
  prioridade TEXT DEFAULT 'Média',
  status TEXT NOT NULL DEFAULT 'PENDENTE_ANALISE',
  criado_em TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  analisado_em TIMESTAMP WITH TIME ZONE,
  finalizado_em TIMESTAMP WITH TIME ZONE,
  sla_horas_limite INTEGER DEFAULT 48,
  sla_cumprido BOOLEAN,
  observacao_triagem TEXT
);

